// Landing sites of the 125 planets of the units (1.62.0): the search of landingSite (src/worlds/field.js)
// takes 0.05 to 0.6 s for a planet, so its results are kept in src/worlds/landing-sites.js and the site does
// not repeat it at every landing. tests/terreno.test.mjs checks the file against the search.
// Usage: node scripts/landing-sites.mjs
import fs from 'node:fs';
import { planetCards } from '../src/worlds/genome.js';
import { landingSite, storedSite } from '../src/worlds/field.js';

export const HEADER = ['// Generated by node scripts/landing-sites.mjs from landingSite in src/worlds/field.js: the landing site of',
    '// each planet of the units, as the unit direction on the sphere and the shift of the local style.',
    'export const LANDING_SITES = Object.freeze(['].join('\n');
/** The module with the sites of the planets in `indices` (all by default). */
export function sitesSource(indices = null) {
    const G = planetCards(), rows = (indices || G.map((_, i) => i)).map(i => '    [' + storedSite(landingSite(G[i])).join(', ') + '],');
    return [HEADER, ...rows, ']);', ''].join('\n');
}
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
    fs.writeFileSync(new URL('../src/worlds/landing-sites.js', import.meta.url), sitesSource());
    console.log('Scritto src/worlds/landing-sites.js');
}
